// Emits dist/tokens.css (:root custom properties) and dist/tailwind-preset.cjs
// from the compiled token source — keeps web + RN in sync from one definition.
import { createRequire } from 'node:module';
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const require = createRequire(import.meta.url);
const here = dirname(fileURLToPath(import.meta.url));
const distDir = join(here, '..', 'dist');

const { cssVars, tailwindThemeExtend } = require(join(distDir, 'index.cjs'));

const rootBody = Object.entries(cssVars)
  .map(([name, value]) => `  ${name}: ${value};`)
  .join('\n');

const css = `/* Generated by @lockin90/tokens — do not edit. */
:root {
${rootBody}
}
`;
writeFileSync(join(distDir, 'tokens.css'), css);

const preset = `// Generated by @lockin90/tokens — do not edit.
/** @type {import('tailwindcss').Config} */
module.exports = {
  theme: {
    extend: ${JSON.stringify(tailwindThemeExtend, null, 4)},
  },
};
`;
writeFileSync(join(distDir, 'tailwind-preset.cjs'), preset);

console.log('[@lockin90/tokens] wrote dist/tokens.css + dist/tailwind-preset.cjs');
