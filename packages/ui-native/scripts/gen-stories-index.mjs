#!/usr/bin/env node
// Generates src/stories/index.ts — a static registry of every *.stories.tsx module,
// consumed by the mobile app's on-device story-variant browser (and anything else
// that wants to render every story variant outside Storybook). Metro needs static
// imports, so this file must be regenerated whenever a story file is added/removed:
//   node scripts/gen-stories-index.mjs
import { readdirSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const storiesDir = join(dirname(fileURLToPath(import.meta.url)), '..', 'src', 'stories');
const files = readdirSync(storiesDir)
  .filter((f) => f.endsWith('.stories.tsx'))
  .sort();

const entries = files.map((f) => {
  const stem = f.replace(/\.stories\.tsx$/, '');
  const ident = `${stem.replace(/[^A-Za-z0-9_$]/g, '_')}Stories`;
  return { stem, ident, spec: `./${stem}.stories` };
});

const out = `// AUTO-GENERATED by scripts/gen-stories-index.mjs — do not edit by hand.
// Static registry of every story module, for on-device story-variant browsers.
/* eslint-disable */
${entries.map((e) => `import * as ${e.ident} from '${e.spec}';`).join('\n')}

/** A single Storybook CSF story export (render-based in this kit). */
export interface StoryDef {
  render?: (args?: Record<string, unknown>) => unknown;
  args?: Record<string, unknown>;
}

/** A story module: \`default\` meta + named story exports. */
export type StoryModule = Record<string, unknown> & { default?: { title?: string } };

export const STORY_MODULES: Record<string, StoryModule> = {
${entries.map((e) => `  ${JSON.stringify(e.stem)}: ${e.ident},`).join('\n')}
};
`;

writeFileSync(join(storiesDir, 'index.ts'), out);
console.log(`wrote src/stories/index.ts with ${entries.length} modules`);
